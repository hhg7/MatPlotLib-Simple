#!/usr/bin/env perl
# Writes lib/Matplotlib/Simple/Colors.pm, the tables of matplotlib's named colors and
# colormaps that the gnuplot and ggplot2 engines draw with, so that "color =>
# 'tab:blue'" and "cmap => 'viridis'" come out the same color whichever engine
# draws them. Neither gnuplot nor R knows matplotlib's names: gnuplot's own
# list is a different one, R's lacks "tab:" and "C0", and the two disagree with
# matplotlib about some of the names they share.
#
# The values are read from matplotlib itself, so they are whatever the python3
# on PATH has installed; the version is written into the module's header.
#
#	perl make.colors.pl
#
# Run it from the repository root. It is not run by the build or the tests: the
# module it writes is committed, and is what they use.
use strict;
use warnings FATAL => 'all';
use feature 'say';

my $out = 'lib/Matplotlib/Simple/Colors.pm';
# The colormaps the matplotlib engine's documentation and defaults name
# (gist_rainbow is the default of hexbin, hist2d and scatter), and the common
# perceptually uniform and diverging ones. Any other is refused by name by
# the gnuplot and ggplot2 engines.
my @cmaps = qw(viridis plasma inferno magma cividis turbo gist_rainbow rainbow jet
 coolwarm bwr seismic RdBu RdYlBu RdYlGn Spectral PiYG PRGn BrBG
 Blues Greens Greys Oranges Purples Reds YlOrRd YlGnBu hot cool spring summer autumn winter gray bone copper);
# Stops per colormap. 17 = 16 equal intervals, which keeps the largest step
# between neighbouring stops of gist_rainbow, the most rapidly changing map
# here, under one eighth of the hue circle; a gradient between stops is drawn
# by gnuplot and R alike.
my $n_stops = 17;
my $python = <<"PYTHON";
import matplotlib, matplotlib.colors as mc
print('VERSION', matplotlib.__version__)
names = {}
for table in (mc.BASE_COLORS, mc.TABLEAU_COLORS, mc.CSS4_COLORS):
	for name in table:
		names[name] = mc.to_hex(name)
for i in range(10):
	names['C%d' % i] = mc.to_hex('C%d' % i)
for name in sorted(names):
	print('COLOR', name, names[name])
for cmap in '@cmaps'.split():
	m = matplotlib.colormaps[cmap]
	print('CMAP', cmap, ' '.join(mc.to_hex(m(i / ($n_stops - 1))) for i in range($n_stops)))
PYTHON
open my $py, '-|', 'python3', '-c', $python or die "can't run python3: $!";
my ( $version, @colors, @maps );
while (<$py>) {
	chomp;
	if (/^VERSION (\S+)/) { $version = $1 }
	elsif (/^COLOR (\S+) (#[0-9a-f]{6})$/) { push @colors, [ $1, $2 ] }
	elsif (/^CMAP (\S+) (.+)$/) { push @maps, [ $1, [ split ' ', $2 ] ] }
	else { die "unexpected line from python: $_" }
}
close $py or die "python3 failed: $?";
die 'no matplotlib version read' unless defined $version;
open my $fh, '>', $out or die "can't write $out: $!";
print {$fh} <<"PERL";
package Matplotlib::Simple::Colors;
use strict;
use warnings FATAL => 'all';
our \$VERSION = 0.33;
# Generated by make.colors.pl in the repository root from matplotlib $version;
# do not edit. Re-run with "perl make.colors.pl".
#
# %named: every name matplotlib.colors gives a color in BASE_COLORS,
# TABLEAU_COLORS ("tab:blue") and CSS4_COLORS, and the property-cycle names
# "C0" to "C9" as matplotlib's default cycle has them, as #rrggbb. The xkcd
# names are left out.
#
# %colormap: each colormap sampled at $n_stops equally spaced points from 0
# to 1, as #rrggbb, low end first. A "_r" name is the reverse, and is worked
# out by the engines rather than stored.
our %named = (
PERL
printf {$fh} "\t%-24s => '%s',\n", "'$_->[0]'", $_->[1] foreach @colors;
say {$fh} ');';
say {$fh} 'our %colormap = (';
say {$fh} "\t$_->[0] => [" . join( q{, }, map { "'$_'" } @{ $_->[1] } ) . "]," foreach @maps;
say {$fh} ');';
say {$fh} '1;';
close $fh or die "can't close $out: $!";
say "wrote $out from matplotlib $version";
